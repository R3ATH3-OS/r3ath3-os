//! `wasm-core` proof. Hand-encoded modules, each with its WAT in a comment.
//! Safe code only. A failed check prints one line and exits through `fail`.

use core::fmt::Write;

use crate::apps;
use crate::frames;
use crate::heap;
use crate::qemu_exit;
use crate::serial;
use crate::wasm::{self, Trap};

pub fn run_core() -> ! {
    let heap_before = heap::used();
    let free_before = frames::stats().1;
    let _ = write!(serial::Writer, "R3ATH3_WASM_CORE start\n");
    step1();
    step2();
    step3();
    step4();
    step5();
    step6();
    step7();
    step8();
    step9();
    step10();
    let heap_after = heap::used();
    let free_after = frames::stats().1;
    if heap_before != heap_after || free_before != free_after {
        fail(11, "changed");
    }
    let _ = write!(serial::Writer, "R3ATH3_WASM_CORE step=11 heap=same frames=same\n");
    let _ = write!(serial::Writer, "R3ATH3_WASM_CORE ok steps=11\n");
    qemu_exit::wasm_core_ok();
}

fn step1() {
    let got = must_call(1, ARITH, "add", &[40, 2], wasm::FUEL_PER_CALL);
    if got != 42 {
        fail_i64(1, "add", got);
    }
    let _ = write!(serial::Writer, "R3ATH3_WASM_CORE step=1 add=42\n");
}

fn step2() {
    let fac = must_call(2, FAC, "fac64", &[20], wasm::FUEL_PER_CALL);
    if fac != 2_432_902_008_176_640_000 {
        fail_i64(2, "fac64", fac);
    }
    let ext = must_call(2, FAC, "ext8", &[0xFF], wasm::FUEL_PER_CALL);
    if ext != -1 {
        fail_i64(2, "ext8", ext);
    }
    // -> i32 that leaves i64::MAX must come back sign-narrowed, not raw.
    let wide = must_call(2, WIDE, "wide", &[], wasm::FUEL_PER_CALL);
    if wide != -1 {
        fail_i64(2, "wide", wide);
    }
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE step=2 fac64=2432902008176640000 ext8=-1\n"
    );
}

fn step3() {
    let fib = must_call(3, FIB, "fib", &[20], wasm::FUEL_PER_CALL);
    if fib != 6765 {
        fail_i64(3, "fib", fib);
    }
    let p0 = must_call(3, FIB, "pick", &[0], wasm::FUEL_PER_CALL);
    let p1 = must_call(3, FIB, "pick", &[1], wasm::FUEL_PER_CALL);
    let p2 = must_call(3, FIB, "pick", &[5], wasm::FUEL_PER_CALL);
    if p0 != 10 || p1 != 20 || p2 != 99 {
        fail(3, "pick");
    }
    let i0 = must_call(3, FIB, "ind", &[0], wasm::FUEL_PER_CALL);
    let i1 = must_call(3, FIB, "ind", &[1], wasm::FUEL_PER_CALL);
    if i0 != 7 || i1 != 8 {
        fail(3, "ind");
    }
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE step=3 fib=6765 pick=10,20,99 ind=7,8\n"
    );
}

fn step4() {
    let value = wasm::with_instance(MEM, |loaded| {
        let mut inst = match loaded {
            Ok(inst) => inst,
            Err(error) => fail(4, error.word()),
        };
        let got = match inst.call("go", &[]) {
            Ok(Some(value)) => value,
            Ok(None) => fail(4, "none"),
            Err(trap) => fail(4, trap.word()),
        };
        let grow1 = match inst.call("grow", &[]) {
            Ok(Some(value)) => value,
            Ok(None) => fail(4, "grow-none"),
            Err(trap) => fail(4, trap.word()),
        };
        let grow2 = match inst.call("grow", &[]) {
            Ok(Some(value)) => value,
            Ok(None) => fail(4, "grow-none"),
            Err(trap) => fail(4, trap.word()),
        };
        let size = match inst.call("size", &[]) {
            Ok(Some(value)) => value,
            Ok(None) => fail(4, "size-none"),
            Err(trap) => fail(4, trap.word()),
        };
        (got, grow1, grow2, size)
    });
    let Some((got, grow1, grow2, size)) = value else {
        fail(4, "arena");
    };
    if got != 305_419_896 || grow1 != 1 || grow2 != -1 || size != 2 {
        fail(4, "mem");
    }
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE step=4 mem=305419896 grow=1,-1 size=2\n"
    );
}

fn step5() {
    let traps = [
        (T_UNREACH, "unreachable"),
        (T_MEM, "memory"),
        (T_DIV, "div-zero"),
        (T_OVF, "overflow"),
        (T_IND, "indirect"),
        (T_STACK, "stack"),
        (T_FUEL, "fuel"),
    ];
    for (module, word) in traps {
        let got = wasm::with_instance(module, |loaded| match loaded {
            Ok(mut inst) => match inst.call("go", &[]) {
                Err(trap) => trap.word(),
                Ok(_) => "ok",
            },
            Err(error) => error.word(),
        });
        match got {
            Some(actual) if actual == word => {}
            Some(actual) => fail(5, actual),
            None => fail(5, "arena"),
        }
    }
    if !underflow_keeps_slots() {
        fail(5, "underflow");
    }
    if !call_arg_traps() {
        fail(5, "call-arg");
    }
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE step=5 traps=unreachable,memory,div-zero,overflow,indirect,stack,fuel\n"
    );
}

/// `go` stores 222, then `bad` stores its parameter 333 and local 111.
/// `bad` then runs `i32.add` on an empty operand stack, keeps that sum, and
/// `i32.store`s it at offset 12 (`i32.const 12` is the address). The add traps
/// `stack` first, so offset 12 stays 0 and the three earlier words stay.
fn underflow_keeps_slots() -> bool {
    let kept = wasm::with_instance(UNDER, |loaded| {
        let mut inst = match loaded {
            Ok(inst) => inst,
            Err(_) => return false,
        };
        if !matches!(inst.call("go", &[]), Err(Trap::Stack)) {
            return false;
        }
        let mem = inst.memory();
        mem_word(mem, 0) == Some(222)
            && mem_word(mem, 4) == Some(333)
            && mem_word(mem, 8) == Some(111)
            && mem_word(mem, 12) == Some(0)
    });
    kept == Some(true)
}

/// Caller sets a local, leaves the operand stack empty, and calls a one-param
/// function. `enter` must trap `stack` instead of using that local as the param.
fn call_arg_traps() -> bool {
    let trapped = wasm::with_instance(CALLARG, |loaded| {
        let mut inst = match loaded {
            Ok(inst) => inst,
            Err(_) => return false,
        };
        matches!(inst.call("go", &[]), Err(Trap::Stack))
    });
    trapped == Some(true)
}

fn mem_word(mem: &[u8], off: usize) -> Option<i32> {
    let bytes = mem.get(off..off + 4)?;
    Some(i32::from_le_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]))
}

fn step6() {
    let dead = wasm::with_instance(T_UNREACH, |loaded| {
        let mut inst = match loaded {
            Ok(inst) => inst,
            Err(_) => return false,
        };
        if !matches!(inst.call("go", &[]), Err(Trap::Unreachable)) {
            return false;
        }
        matches!(inst.call("go", &[]), Err(Trap::Dead))
    });
    if dead != Some(true) {
        fail(6, "dead");
    }
    let fresh = must_call(6, ARITH, "add", &[40, 2], wasm::FUEL_PER_CALL);
    if fresh != 42 {
        fail_i64(6, "fresh", fresh);
    }
    let _ = write!(serial::Writer, "R3ATH3_WASM_CORE step=6 after-trap=dead fresh=42\n");
}

fn step7() {
    let wrote = wasm::with_instance(FRESH, |loaded| {
        let mut inst = match loaded {
            Ok(inst) => inst,
            Err(_) => return false,
        };
        matches!(inst.call("write", &[]), Ok(_))
    });
    if wrote != Some(true) {
        fail(7, "write");
    }
    let read = must_call(7, FRESH, "read", &[], wasm::FUEL_PER_CALL);
    if read != 0 {
        fail_i64(7, "fresh-memory", read);
    }
    let _ = write!(serial::Writer, "R3ATH3_WASM_CORE step=7 fresh-memory=0\n");
}

fn step8() {
    let cases = [
        (BAD_MAGIC, "magic"),
        (BAD_VERSION, "version"),
        (BAD_TRUNC, "truncated"),
        (BAD_SECTION, "section"),
        (BAD_OPCODE, "opcode"),
        (BAD_FLOAT, "float"),
        (BAD_IMPORT, "import"),
        (BAD_LIMITS, "limits"),
    ];
    for (module, word) in cases {
        let got = wasm::with_instance(module, |loaded| match loaded {
            Err(error) => error.word(),
            Ok(_) => "loaded",
        });
        match got {
            Some(actual) if actual == word => {}
            Some(actual) => fail(8, actual),
            None => fail(8, "arena"),
        }
    }
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE step=8 refused=magic,version,truncated,section,opcode,float,import,limits\n"
    );
}

fn step9() {
    // A prefix that is itself a well-formed module (magic and version, or a
    // complete earlier section) loads. It must not run `add` to 42.
    for len in 0..ARITH.len() {
        let prefix = &ARITH[..len];
        let bad = wasm::with_instance(prefix, |loaded| match loaded {
            Err(_) => false,
            Ok(mut inst) => matches!(
                inst.call_with_fuel("add", &[40, 2], 10_000),
                Ok(Some(42))
            ),
        });
        if bad != Some(false) {
            fail(9, "prefix");
        }
    }
    const FLIPS: [u8; 8] = [0x00, 0x01, 0x0B, 0x20, 0x41, 0x7F, 0x80, 0xFF];
    let mut buf = [0u8; 64];
    let len = ARITH.len();
    buf[..len].copy_from_slice(ARITH);
    for index in 0..len {
        let saved = buf[index];
        for flip in FLIPS {
            buf[index] = flip;
            let hung = wasm::with_instance(&buf[..len], |loaded| match loaded {
                Err(_) => false,
                Ok(mut inst) => {
                    let _ = inst.call_with_fuel("add", &[40, 2], 10_000);
                    false
                }
            });
            if hung != Some(false) {
                fail(9, "flip");
            }
        }
        buf[index] = saved;
    }
    let _ = write!(serial::Writer, "R3ATH3_WASM_CORE step=9 prefixes=ok flips=ok\n");
}

fn step10() {
    let hello = wasm::with_instance(apps::HELLO, |loaded| match loaded {
        Ok(mut inst) => apps::check_abi(&mut inst),
        Err(_) => false,
    });
    if hello != Some(true) {
        fail(10, "hello");
    }
    let spin = wasm::with_instance(apps::SPIN, |loaded| match loaded {
        Ok(mut inst) => {
            if !apps::check_abi(&mut inst) {
                return false;
            }
            matches!(inst.call("r3_step", &[]), Err(Trap::Fuel))
        }
        Err(_) => false,
    });
    if spin != Some(true) {
        fail(10, "spin");
    }
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE step=10 hello=abi-ok spin-init=fuel\n"
    );
}

fn must_call(step: u32, module: &[u8], name: &str, args: &[i64], fuel: u32) -> i64 {
    let value = wasm::with_instance(module, |loaded| match loaded {
        Ok(mut inst) => match inst.call_with_fuel(name, args, fuel) {
            Ok(Some(value)) => Ok(value),
            Ok(None) => Err("none"),
            Err(trap) => Err(trap.word()),
        },
        Err(error) => Err(error.word()),
    });
    match value {
        Some(Ok(value)) => value,
        Some(Err(word)) => fail(step, word),
        None => fail(step, "arena"),
    }
}

fn fail(step: u32, detail: &str) -> ! {
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE fail step={step} {detail}\n"
    );
    qemu_exit::fail();
}

fn fail_i64(step: u32, what: &str, got: i64) -> ! {
    let _ = write!(
        serial::Writer,
        "R3ATH3_WASM_CORE fail step={step} {what}={got}\n"
    );
    qemu_exit::fail();
}

